package com.ims.dtos.inventory;

import com.ims.enums.PaymentMethod;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class PurchaseInvoiceCreateRequest {

    private String invoiceNumber; // Auto-generated by backend if blank

    private String supplierInvoiceNumber;

    @NotNull(message = "Supplier ID is required")
    private Long supplierId;

    @NotNull(message = "Invoice date is required")
    private LocalDate invoiceDate;

    private LocalDate purchaseDate;
    private LocalDate expectedDeliveryDate;
    private String branchWarehouse;

    private Long vehicleId; // If direct parts purchase for vehicle
    private Long jobCardId; // If direct parts purchase for job card

    private BigDecimal discountAmount;
    private BigDecimal freightCharge;
    private BigDecimal otherCharges;

    // Payment options at time of purchase
    private BigDecimal amountPaidNow; // 0 for credit purchase, total for full payment, < total for partial
    private PaymentMethod paymentMethod;
    private String paymentReference;

    private String notes;
    private String documentPath;

    @NotEmpty(message = "At least one purchase item is required")
    private List<InvoiceItemRequest> items;

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class InvoiceItemRequest {
        @NotNull(message = "Part ID is required")
        private Long partId;

        @NotNull(message = "Quantity is required")
        private Integer quantity;

        @NotNull(message = "Unit price is required")
        @DecimalMin(value = "0.0", inclusive = true)
        private BigDecimal unitPrice;

        private BigDecimal lineDiscount;
        private BigDecimal taxPercentage;
    }
}
